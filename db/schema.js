/**
 * Схема базы PostgreSQL. Версия хранится в schema_meta; обновления — в UPGRADES (ключ — версия, до которой обновляем).
 *
 * Даты — текст ISO 8601 (UTC), как их выдаёт toISOString(): так они сравниваются и сортируются как строки,
 * а курсор страниц заказов (created_at, id) не зависит от часового пояса сервера базы.
 * row_no — порядок добавления записи (в SQLite им был rowid): по нему упорядочиваются записи с одинаковыми полями сортировки.
 */

const SCHEMA_VERSION = 1;

/**
 * Ключ pg_advisory_xact_lock: все пишущие транзакции выполняются по очереди, как BEGIN IMMEDIATE в SQLite.
 * Так проверка «есть ли такой клиент» и вставка, номер документа, списание остатков не пересекаются с чужими.
 */
const WRITE_LOCK = 4242001;

/** Таблицы в порядке создания и заполнения (order_items ссылается на orders). */
const TABLES = ["schema_meta", "settings", "products", "clients", "orders", "order_items", "doc_counters", "documents", "document_sends"];

/** Таблицы с данными — для копий и проверки числа записей. */
const DATA_TABLES = TABLES.filter((name) => name !== "schema_meta");

const SCHEMA = `
CREATE TABLE schema_meta (
  id         INTEGER PRIMARY KEY CHECK (id = 1),
  version    INTEGER NOT NULL,
  created_at TEXT NOT NULL
);

-- Строка для поиска без учёта регистра: «Ёлкин» и «елкин» совпадают. Явная таблица кириллицы (с казахскими буквами):
-- lower() сворачивает её, только если база создана с локалью UTF-8, а не C.
CREATE FUNCTION bz_fold(value TEXT) RETURNS TEXT
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$ SELECT translate(lower(coalesce(value, '')),
    'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯёӘҒҚҢӨҰҮҺІ',
    'абвгдеежзийклмнопрстуфхцчшщъыьэюяеәғқңөұүһі') $$;

CREATE FUNCTION bz_digits(value TEXT) RETURNS TEXT
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$ SELECT regexp_replace(coalesce(value, ''), '[^0-9]', '', 'g') $$;

-- Поле из JSON-текста; повреждённый JSON — NULL, а не ошибка всего запроса.
CREATE FUNCTION bz_json_field(value TEXT, field TEXT) RETURNS TEXT
  LANGUAGE sql STABLE PARALLEL SAFE
  AS $$ SELECT CASE WHEN value IS NOT NULL AND pg_input_is_valid(value, 'jsonb') THEN (value::jsonb) ->> field END $$;

CREATE TABLE settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- stock: NULL — остаток не учитывается (продаётся без ограничений), число — сколько можно продать.
CREATE TABLE products (
  id             TEXT PRIMARY KEY,
  row_no         BIGINT GENERATED BY DEFAULT AS IDENTITY,
  sort_order     INTEGER NOT NULL,
  title          TEXT NOT NULL,
  description    TEXT NOT NULL DEFAULT '',
  title_kk       TEXT NOT NULL DEFAULT '',
  description_kk TEXT NOT NULL DEFAULT '',
  price          DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (price >= 0),
  currency       TEXT NOT NULL DEFAULT 'KZT' CHECK (currency IN ('KZT', 'RUB', 'USD')),
  kind           TEXT NOT NULL DEFAULT 'service' CHECK (kind IN ('service', 'product')),
  category       TEXT NOT NULL,
  image          TEXT NOT NULL,
  stock          INTEGER CHECK (stock IS NULL OR stock >= 0)
);
CREATE INDEX products_sort ON products (sort_order, row_no);

-- requisites — JSON с реквизитами покупателя (юрлицо, БИН/ИИН, адрес, банк, e-mail).
CREATE TABLE clients (
  id         TEXT PRIMARY KEY,
  row_no     BIGINT GENERATED BY DEFAULT AS IDENTITY,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  name       TEXT NOT NULL DEFAULT '',
  phone      TEXT NOT NULL DEFAULT '',
  phone_key  TEXT NOT NULL DEFAULT '',
  name_key   TEXT NOT NULL DEFAULT '',
  note       TEXT NOT NULL DEFAULT '',
  source     TEXT NOT NULL DEFAULT 'manual',
  extra      TEXT,
  requisites TEXT
);
CREATE INDEX clients_phone_key ON clients (phone_key);
CREATE INDEX clients_name_key ON clients (name_key);

-- client_id без внешнего ключа: карточку клиента можно удалить, заказы при этом остаются.
-- discount / delivery — скидка на заказ и доставка суммой в валюте adjust_currency.
-- vat_rate — ставка НДС в процентах, уже включённого в цены; 0 — «Без НДС».
CREATE TABLE orders (
  id              TEXT PRIMARY KEY,
  row_no          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  created_at      TEXT NOT NULL,
  updated_at      TEXT NOT NULL,
  channel         TEXT NOT NULL,
  status          TEXT NOT NULL DEFAULT 'new',
  customer_name   TEXT NOT NULL DEFAULT '',
  customer_phone  TEXT NOT NULL DEFAULT '',
  client_id       TEXT,
  total_text      TEXT NOT NULL DEFAULT '',
  message         TEXT NOT NULL DEFAULT '',
  source_page     TEXT NOT NULL DEFAULT '',
  note            TEXT,
  lead_direction  TEXT,
  lead_comment    TEXT,
  extra           TEXT,
  discount        DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (discount >= 0),
  delivery        DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (delivery >= 0),
  adjust_currency TEXT NOT NULL DEFAULT 'KZT',
  vat_rate        DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (vat_rate >= 0 AND vat_rate < 100)
);
CREATE INDEX orders_created_id ON orders (created_at, id);
CREATE INDEX orders_status_created ON orders (status, created_at, id);
CREATE INDEX orders_channel_status ON orders (channel, status, created_at, id);
CREATE INDEX orders_client ON orders (client_id);

-- reserved: сколько штук сейчас удержано за незакрытым заказом (вычтено из stock).
-- consumed: сколько штук уже выдано покупателю. На склад само не возвращается.
-- discount — скидка на позицию суммой в валюте позиции.
CREATE TABLE order_items (
  order_id   TEXT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  position   INTEGER NOT NULL,
  product_id TEXT NOT NULL DEFAULT '',
  title      TEXT NOT NULL DEFAULT '',
  qty        INTEGER NOT NULL DEFAULT 1,
  price      DOUBLE PRECISION NOT NULL DEFAULT 0,
  currency   TEXT NOT NULL DEFAULT 'KZT',
  line_total DOUBLE PRECISION,
  kind       TEXT NOT NULL DEFAULT 'service',
  reserved   INTEGER NOT NULL DEFAULT 0,
  consumed   INTEGER NOT NULL DEFAULT 0,
  discount   DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (discount >= 0),
  PRIMARY KEY (order_id, position)
);
CREATE INDEX order_items_product ON order_items (product_id);

CREATE TABLE doc_counters (
  kind TEXT NOT NULL,
  year INTEGER NOT NULL,
  last INTEGER NOT NULL,
  PRIMARY KEY (kind, year)
);

-- Учётные документы (счета, акты). snapshot — все данные документа на момент выпуска:
-- PDF всегда строится из него, поэтому повторное скачивание даёт тот же документ.
-- order_id без внешнего ключа: выпущенный документ остаётся и после удаления заказа.
CREATE TABLE documents (
  id          TEXT PRIMARY KEY,
  kind        TEXT NOT NULL CHECK (kind IN ('invoice', 'act')),
  year        INTEGER NOT NULL,
  seq         INTEGER NOT NULL,
  number      TEXT NOT NULL,
  order_id    TEXT NOT NULL,
  currency    TEXT NOT NULL,
  status      TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'annulled')),
  created_at  TEXT NOT NULL,
  annulled_at TEXT,
  replaced_by TEXT,
  total       DOUBLE PRECISION NOT NULL,
  source_hash TEXT NOT NULL,
  snapshot    TEXT NOT NULL,
  UNIQUE (kind, year, seq)
);
CREATE INDEX documents_order ON documents (order_id, kind, currency, status);

CREATE TABLE document_sends (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id TEXT NOT NULL,
  channel     TEXT NOT NULL,
  recipient   TEXT NOT NULL DEFAULT '',
  sent_at     TEXT NOT NULL,
  ok          BOOLEAN NOT NULL,
  error       TEXT
);
CREATE INDEX document_sends_doc ON document_sends (document_id);
`;

