const BLOCK_FIELDS = ["h2", "p", "tip", "ul", "ol"];

/** Переносит перевод в поля _kk статьи (title_kk, q_kk, text_kk, ul_kk …). Без перевода статья не меняется. */
export function applyKazakh(article) {
  const kk = ARTICLES_KK[article.slug];
  if (!kk) return article;
  const out = { ...article, title_kk: kk.title, excerpt_kk: kk.excerpt };
  if (article.body && kk.body) {
    out.body = article.body.map((block, index) => {
      const field = BLOCK_FIELDS.find((name) => name in block);
      const text = kk.body[index];
      return field && text != null ? { ...block, [field + "_kk"]: text } : block;
    });
  }
  if (article.questions && kk.questions) {
    out.questions = article.questions.map((question, index) => {
      const own = kk.questions[index];
      if (!own) return question;
      return {
        ...question,
        q_kk: own.q,
        options: question.options.map((option, i) => (own.options[i] ? { ...option, text_kk: own.options[i] } : option)),
      };
    });
  }
  if (article.results && kk.results) {
    out.results = article.results.map((result, index) =>
      kk.results[index] ? { ...result, title_kk: kk.results[index].title, text_kk: kk.results[index].text } : result
    );
  }
  if (article.cta && kk.cta) out.cta = { ...article.cta, title_kk: kk.cta.title, text_kk: kk.cta.text };
  return out;
}
