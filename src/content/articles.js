/** Публикации этого сайта: по разделу каталога, к которому относится статья. */
const SITE_ARTICLES = ARTICLES.filter((item) => siteHasCategory(item.category));

export function findArticle(slug) {
  return SITE_ARTICLES.find((item) => item.slug === slug) || null;
}

/** Последние публикации, новые сверху. */
export function sortedArticles() {
  return [...SITE_ARTICLES].sort((a, b) => String(b.date).localeCompare(String(a.date)));
}

export function quizMaxScore(test) {
  return test.questions.reduce((sum, question) => sum + Math.max(...question.options.map((o) => o.score)), 0);
}

export function quizResult(test, score) {
  return [...test.results].sort((a, b) => b.min - a.min).find((result) => score >= result.min) || test.results[0];
}
